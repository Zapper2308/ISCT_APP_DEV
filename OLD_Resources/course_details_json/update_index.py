"""Update the course index and local-preview data: python course_details/update_index.py"""

import json
from pathlib import Path


def update_index(folder=None):
    folder = Path(folder) if folder else Path(__file__).resolve().parent
    files = sorted(
        path.name for path in folder.glob('*.json')
        if not path.name.startswith('_') and path.name != 'index.json'
    )
    courses = {}
    for filename in files:
        try:
            with (folder / filename).open(encoding='utf-8-sig') as source:
                course = json.load(source)
            if not isinstance(course, dict):
                raise ValueError('Each course file must contain a JSON object.')
            courses[filename] = course
        except (ValueError, OSError) as error:
            raise SystemExit(f'{filename}: {error}\nCourse index and local-preview data were not changed.')
    destination = folder / 'index.json'
    temporary = folder / 'index.json.tmp'
    temporary.write_text(json.dumps(files, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    preview = folder / 'catalog.js'
    preview_temporary = folder / 'catalog.js.tmp'
    preview_temporary.write_text(
        '// Generated from the course JSON files. Run update_index.py after editing; do not edit this file.\n'
        + 'window.ISCT_COURSE_SNAPSHOT = '
        + json.dumps({'files': files, 'courses': courses}, ensure_ascii=True, indent=2)
        + ';\n',
        encoding='utf-8',
    )
    preview_temporary.replace(preview)
    temporary.replace(destination)
    print(f'Updated {len(files)} course files and local-preview data. Refresh the website to load them.')


if __name__ == '__main__':
    update_index()
